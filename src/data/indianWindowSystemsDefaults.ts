export function isWindowSystemFormulaReady(system: WindowSystemDefinition): boolean {
  if (system.usesLegacySlidingEngine === '2-track' || system.usesLegacySlidingEngine === '3-track') {
    return true;
  }
  if (!system.formulaConfigured) return false;
  return Array.isArray(system.profileSeries) && system.profileSeries.some((p) => p.isConfigured);
}
